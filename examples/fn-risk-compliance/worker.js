// ── seams (template §7.4 — emitted, never rendered; no account UI here) ────
function emitSeam(env, event) {
  const line = JSON.stringify({ ...seamTags, ts: new Date().toISOString(), ...event })
  if (globalThis.__SEAM_SILENT !== true) console.log(line)
  if (env && env.SEAMS && typeof env.SEAMS.send === 'function') {
    try {
      env.SEAMS.send(JSON.parse(line))
    } catch {
      /* the seam is best-effort transport, never a request failure */
    }
  }
}

function identityClass(request) {
  // id.org.ai grain is not wired at wave zero — only the CLASS is derivable.
  const mode = request.headers.get('sec-fetch-mode')
  const dest = request.headers.get('sec-fetch-dest')
  if (mode === 'navigate' || dest === 'document') return 'human-browser'
  const ua = (request.headers.get('user-agent') || '').toLowerCase()
  if (AGENT_UA_TOKENS.some((t) => ua.includes(t))) return 'machine-agent'
  return 'machine-unattributed'
}

// ── three-faced serving for this worker's own GET addresses ────────────────
function threeFaces(title, obj) {
  const json = obj
  const md = `# ${title}\n\n\`\`\`json\n${JSON.stringify(obj, null, 2)}\n\`\`\`\n`
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const html = `<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><title>${esc(title)}</title></head>\n<body><h1>${esc(title)}</h1><pre>${esc(JSON.stringify(obj, null, 2))}</pre></body></html>\n`
  return { json, md, html }
}

