// ── domain views (typed envelopes; the record IS the wire truth) ────────────
const listOf = (map) => [...map.values()]

function getRecord(map, id, what) {
  const rec = map.get(id)
  if (rec === undefined) return { status: 200, body: empty(`no ${what} with id ${id} — a truthful empty result, not an error`) }
  return { status: 200, body: ok([rec]) }
}

// ── MCP (same definition, JSON-RPC transport; authless anon-sandbox rung) ──
const mcpTools = {
  listStatutes: { description: 'List the family’s statutes (public-law citation records, provenance disclosed)', input: {}, call: () => listOf(state.statutes) },
  getStatute: { description: 'Get one statute by id', input: { statuteId: 'string' }, call: (a) => state.statutes.get(String(a.statuteId)) ?? null },
  listChecks: {
    description: 'List check definitions (the family register of held per-statute .dev fronts); optional filters statuteId, front',
    input: { statuteId: 'string?', front: 'string?' },
    call: (a) => listOf(state.checks).filter((c) => (a.statuteId ? c.statuteId === a.statuteId : true) && (a.front ? c.front === a.front : true)),
  },
  getCheck: { description: 'Get one check definition by id', input: { checkId: 'string' }, call: (a) => state.checks.get(String(a.checkId)) ?? null },
  runCheck: {
    description: 'Run a check against a subject (labeled synthetic result; ephemeral; attested: false — no live registry consulted at wave zero)',
    input: { checkId: 'string', subject: 'object?' },
    call: (a) => mintRun(String(a.checkId), a.subject && typeof a.subject === 'object' ? a.subject : {}),
  },
  listCheckRuns: { description: 'List check runs (labeled demo seed + anything minted in this isolate)', input: {}, call: () => listOf(state.checkRuns) },
  getCheckRun: { description: 'Get one check run by id', input: { runId: 'string' }, call: (a) => state.checkRuns.get(String(a.runId)) ?? null },
  listObligations: { description: 'List compliance-calendar obligations (labeled demo seed)', input: {}, call: () => listOf(state.obligations) },
  getObligation: { description: 'Get one obligation by id', input: { obligationId: 'string' }, call: (a) => state.obligations.get(String(a.obligationId)) ?? null },
}

/** The shared check-runner: ONE pipeline for the whole family (family grain). */
function mintRun(checkId, subject) {
  const check = state.checks.get(checkId)
  if (!check) return null
  state.minted += 1
  const label = (v) => (typeof v === 'string' && !v.startsWith('[demo]') ? `[demo] ${v}` : v)
  const labeledSubject = Object.fromEntries(Object.entries(subject).map(([k, v]) => [k, typeof v === 'string' ? label(v) : v]))
  const rec = {
    id: `run-anon-${state.minted}`,
    $type: 'https://schema.org.ai/CheckRun',
    example: true, // everything minted in the anon sandbox is example data by definition
    title: `[demo] ${check.front} check run (anon sandbox)`,
    checkId,
    statuteId: check.statuteId,
    subject: labeledSubject,
    verdict: check.statuteId
      ? 'indeterminate — wave-zero sandbox: no live registry is consulted; this run exercises the pipeline shape only'
      : 'unbound — this front’s statute binding is [UNVERIFIED] in the register; no check logic is improvised for it',
    findings: [],
    attested: false,
    attestationRail: ATTESTATION_RAIL,
    workspace: 'anon',
    retention: RETENTION,
  }
  state.checkRuns.set(rec.id, rec)
  return rec
}

function mcpResponse(id, result) {
  return new Response(JSON.stringify({ jsonrpc: '2.0', id, result }), { status: 200, headers: { 'content-type': 'application/json; charset=utf-8' } })
}
function mcpError(id, code, message) {
  return new Response(JSON.stringify({ jsonrpc: '2.0', id, error: { code, message } }), { status: 200, headers: { 'content-type': 'application/json; charset=utf-8' } })
}

async function handleMcp(request, env) {
  let msg
  try {
    msg = await request.json()
  } catch {
    return mcpError(null, -32700, 'parse error — the /mcp door speaks JSON-RPC 2.0')
  }
  const { id = null, method, params = {} } = msg || {}
  if (method === 'initialize') {
    return mcpResponse(id, {
      protocolVersion: '2024-11-05',
      capabilities: { tools: {} },
      serverInfo: { name: 'fn-risk-compliance.org.ai', version: '0.1.0' },
    })
  }
  if (method === 'notifications/initialized') return new Response(null, { status: 202 })
  if (method === 'tools/list') {
    return mcpResponse(id, {
      tools: Object.entries(mcpTools).map(([name, t]) => ({
        name,
        description: t.description,
        inputSchema: { type: 'object', properties: Object.fromEntries(Object.entries(t.input).map(([k, v]) => [k, { type: String(v).replace('?', '') }])) },
      })),
    })
  }
  if (method === 'tools/call') {
    const tool = mcpTools[params.name]
    if (!tool) return mcpError(id, -32602, `unknown tool ${JSON.stringify(params.name)} — tools/list names every tool that exists`)
    emitSeam(env, { seam: 'meter', operation: params.name, shape: 'anon-sandbox', transport: 'mcp' })
    const result = tool.call(params.arguments || {})
    return mcpResponse(id, { content: [{ type: 'text', text: JSON.stringify(result, null, 2) }], isError: false })
  }
  return mcpError(id, -32601, `method ${JSON.stringify(method)} is not served — this door answers initialize, tools/list, tools/call`)
}

// ── router ──────────────────────────────────────────────────────────────────
export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url)
    const path = url.pathname
    const method = request.method

    emitSeam(env, {
      seam: 'traffic',
      path,
      method,
      identity: null, // id.org.ai grain not wired at wave zero — class only
      identityClass: identityClass(request),
      referral: request.headers.get('referer') || null,
    })

    // 1. the card (generator-emitted whole — links.verify and g2 are native)
    if (path === '/.well-known/agents.json' && (method === 'GET' || method === 'HEAD')) {
      return new Response(method === 'HEAD' ? null : JSON.stringify(card, null, 2), {
        status: 200,
        headers: { 'content-type': 'application/json; charset=utf-8' },
      })
    }

    // 2. the headless door BEFORE the generator (its mounted paths answer 405
    //    to non-GET; this POST is a real system-of-record door)
    const runMatch = path.match(/^\/checks\/([^/]+)\/runs$/)
    if (runMatch && method === 'POST') {
      let input
      try {
        input = await request.json()
      } catch {
        return envelopeResponse({ type: 'BLOCKED', reason: 'the check-runner door takes a JSON body: { subject }' }, { status: 403 })
      }
      if (!input || typeof input.subject !== 'object' || input.subject === null) {
        return envelopeResponse({ type: 'BLOCKED', reason: 'subject (object) is required — { subject: { … } }' }, { status: 403 })
      }
      const checkId = decodeURIComponent(runMatch[1])
      const rec = mintRun(checkId, input.subject)
      if (rec === null) {
        return envelopeResponse(empty(`no check definition with id ${checkId} — a truthful empty result, not an error`))
      }
      emitSeam(env, { seam: 'meter', operation: 'runCheck', shape: 'anon-sandbox' })
      return envelopeResponse(ok([rec], { extra: { retention: RETENTION } }), { status: 201 })
    }

    // 3. the MCP door (authless — the anon-sandbox rung only)
    if (path === '/mcp') {
      if (method !== 'POST') {
        return envelopeResponse({ type: 'BLOCKED', reason: 'the /mcp door speaks JSON-RPC 2.0 over POST' }, { status: 405, headers: { allow: 'POST' } })
      }
      return handleMcp(request, env)
    }

    // 4. the generated machine face (quartet, branching collection, offer, home)
    const hit = await axp(request, env)
    if (hit !== undefined) {
      if (path === manifest.collection.path && method === 'GET') {
        emitSeam(env, { seam: 'meter', operation: 'listChecks', shape: 'anon-sandbox' })
      }
      if (hit.status === 402) {
        // money seam: an OFFER was presented. Nothing settles at wave zero —
        // the event exists so the rail ledger can count the boundary.
        emitSeam(env, { seam: 'money', event: 'offer-presented', operation: path === manifest.pricing.offerPath ? 'getOffer' : 'listChecks', settlement: 'none — stub rate card' })
      }
      return hit
    }

    // 5. this worker's own GET addresses (conneg-served, three faces)
    if (method === 'GET' || method === 'HEAD') {
      const { face, cleanPath } = negotiate(request, path)

      const serve = (title, obj, operation, faces) => {
        if (operation) emitSeam(env, { seam: 'meter', operation, shape: 'anon-sandbox' })
        return serveFace(request, url, faces || threeFaces(title, obj), face, { cleanPath })
      }

      if (cleanPath === '/statutes') return serve('fn-risk-compliance — statutes (public-law citation records)', ok(listOf(state.statutes)), 'listStatutes')
      if (cleanPath === '/check-runs') return serve('fn-risk-compliance — check runs (labeled demo seed)', ok(listOf(state.checkRuns)), 'listCheckRuns')
      if (cleanPath === '/obligations') return serve('fn-risk-compliance — obligations (labeled demo seed)', ok(listOf(state.obligations)), 'listObligations')
      if (cleanPath === '/icp' || path === '/icp.json') return serve('fn-risk-compliance — icp (G2 coordinates + agent classes)', icpDocument, null)
      if (cleanPath === '/verify') return serve('fn-risk-compliance — run our tests', verifyPage, null)
      if (cleanPath === '/verify/suite') return serve('fn-risk-compliance — the published suite document', suiteDocument, null)

      const statuteMatch = cleanPath.match(/^\/statutes\/([^/]+)$/)
      if (statuteMatch) {
        const { body } = getRecord(state.statutes, decodeURIComponent(statuteMatch[1]), 'statute')
        return serve(`fn-risk-compliance — statute ${statuteMatch[1]}`, body, 'getStatute')
      }
      const checkMatch = cleanPath.match(/^\/checks\/([^/]+)$/)
      if (checkMatch) {
        const { body } = getRecord(state.checks, decodeURIComponent(checkMatch[1]), 'check definition')
        return serve(`fn-risk-compliance — check ${checkMatch[1]}`, body, 'getCheck')
      }
      const runGetMatch = cleanPath.match(/^\/check-runs\/([^/]+)$/)
      if (runGetMatch) {
        const { body } = getRecord(state.checkRuns, decodeURIComponent(runGetMatch[1]), 'check run')
        return serve(`fn-risk-compliance — check run ${runGetMatch[1]}`, body, 'getCheckRun')
      }
      const obMatch = cleanPath.match(/^\/obligations\/([^/]+)$/)
      if (obMatch) {
        const { body } = getRecord(state.obligations, decodeURIComponent(obMatch[1]), 'obligation')
        return serve(`fn-risk-compliance — obligation ${obMatch[1]}`, body, 'getObligation')
      }
    }

    // 6. typed 404 — nothing here was deleted; the route was never written
    return envelopeResponse(
      { type: 'EMPTY', results: [], message: `no route at ${path} — nothing here has been deleted; the route was never written` },
      { status: 404 },
    )
  },
}
