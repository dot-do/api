#!/usr/bin/env node
/**
 * ingest-facilities.mjs — writes ../facilities.real.mjs from EPA ECHO's
 * public RCRA facility search (echodata.epa.gov). Re-run to refresh; the
 * output file is GENERATED and never hand-edited.
 *
 * Source class: public U.S. government data (public domain, 17 U.S.C. § 105),
 * keyless REST — the register row's "public-licensable ingest" route, probed
 * reachable in-session 2026-08-23. This is the Facility noun's Class-A
 * corpus (binding: ingested). The e-Manifest feed, by contrast, answered
 * 401 in-session (RCRAInfo API requires registered credentials), so the
 * Manifest noun stays a labeled synthetic sandbox seed at wave zero.
 *
 * Scope kept deliberately small (one state, first N active handlers across
 * the universe mix ECHO returns) — the sandbox needs substance, not bulk.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const BASE = "https://echodata.epa.gov/echo";
const QUERY = { p_st: "TX", p_act: "Y" }; // active RCRA handlers, Texas

const search = new URL(`${BASE}/rcra_rest_services.get_facilities`);
search.searchParams.set("output", "JSON");
for (const [k, v] of Object.entries(QUERY)) search.searchParams.set(k, v);

const res1 = await fetch(search);
if (!res1.ok) throw new Error(`get_facilities ${res1.status}`);
const { Results: head } = await res1.json();
if (head.Message !== "Success") throw new Error(`get_facilities: ${head.Message}`);

const page = new URL(`${BASE}/rcra_rest_services.get_qid`);
page.searchParams.set("output", "JSON");
page.searchParams.set("qid", head.QueryID);
page.searchParams.set("pageno", "1");

const res2 = await fetch(page);
if (!res2.ok) throw new Error(`get_qid ${res2.status}`);
const { Results: results } = await res2.json();

const retrievedAt = new Date().toISOString();
const provenance = {
  kind: "ingested",
  source: `${BASE}/rcra_rest_services.get_facilities`,
  query: QUERY,
  retrievedAt,
  license: "U.S. government work — public domain (17 U.S.C. § 105)",
  note:
    "REAL public RCRA handler records ingested from EPA ECHO. Not synthetic, not example-labeled. Fields are as published by the source at retrievedAt; refresh via scripts/ingest-facilities.mjs.",
};

const facilities = (results.Facilities || []).slice(0, 10).map((f) => ({
  $type: "https://schema.org.ai/Facility",
  id: `fac_echo_${f.SourceID}`,
  handlerId: f.SourceID,
  frsRegistryId: f.RegistryID,
  name: f.RCRAName,
  street: f.RCRAStreet,
  city: f.RCRACity,
  county: f.RCRACounty,
  state: f.RCRAState,
  zip: f.RCRAZip,
  epaRegion: f.RCRAEPARegion,
  naics: f.RCRANAICS,
  universe: f.RCRAUniverse,
  rcraStatus: f.RCRAStatus,
  complianceStatus: f.RCRAComplStatus,
  snc: f.RCRASNC,
  inspectionCount: f.RCRAInspCnt,
  lat: f.FacLat,
  long: f.FacLong,
  real: true,
  provenance,
}));

if (facilities.length === 0) throw new Error("no facilities returned — refusing to write an empty corpus");

const banner = `/**
 * facilities.real.mjs — GENERATED by scripts/ingest-facilities.mjs (do not
 * hand-edit; re-run the script to refresh). REAL public data, ingested —
 * the Facility noun's Class-A corpus (EPA ECHO RCRA handler search, public
 * domain). Every record carries its provenance; nothing here is synthetic
 * and nothing is labeled example. Synthetic sandbox records (seed.mjs)
 * deliberately never reference these real parties.
 */

export const FACILITIES_PROVENANCE = Object.freeze(${JSON.stringify(provenance, null, 2)});

export const facilities = ${JSON.stringify(facilities, null, 2)};
`;

writeFileSync(join(HERE, "..", "facilities.real.mjs"), banner);
console.log(`wrote facilities.real.mjs — ${facilities.length} real RCRA handler records (retrievedAt ${retrievedAt})`);
