/**
 * ingest-licenses.mjs — reseed the REAL EstablishmentLicense corpus
 * (§5.2.5: reseeding is a build step, not a manual act).
 *
 * Source (probed reachable in-session, 2026-08-23, keyless 200 OK):
 *   Texas Department of Licensing and Regulation (TDLR) — "TDLR All
 *   Licenses" open dataset on the State of Texas Open Data Portal
 *   (data.texas.gov, Socrata resource 7358-krk7). Cosmetology
 *   establishment (salon) licenses are the NAICS 8121 establishment
 *   grain — the register row's "state cosmetology licensure as the G1
 *   credential registry" route, at the establishment (business) grain.
 *
 * Scope — complete within its stated bounds, never a vague sample:
 *   every license of type "Full Service Establishment" (the full-service
 *   salon license class) with business_county = TRAVIS. One county, one
 *   license class, the whole class within it.
 *
 * Curation (disclosed, presence-when-true): the source rows carry
 * owner_name, telephone numbers, street and mailing addresses, and
 * geocodes. Establishment owner names are frequently personal names of
 * sole proprietors, so the ingest WITHHOLDS person-adjacent and
 * street-grain fields at wave zero (kept: license number/type/subtype,
 * business name, city/state/zip line, county, expiration). The withheld
 * field list is served in the corpus provenance — a curation decision
 * recorded, not silent redaction.
 *
 * Run: node scripts/ingest-licenses.mjs
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const RESOURCE = "https://data.texas.gov/resource/7358-krk7.json";
const WHERE = "business_county='TRAVIS' AND license_type='Full Service Establishment'";
const PAGE = 2000;

const rows = [];
for (let offset = 0; ; offset += PAGE) {
  const url = `${RESOURCE}?$where=${encodeURIComponent(WHERE)}&$order=license_number&$limit=${PAGE}&$offset=${offset}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`TDLR fetch failed: ${res.status} ${res.statusText}`);
  const page = await res.json();
  rows.push(...page);
  if (page.length < PAGE) break;
}

const licenses = rows
  .map((r) => ({
    $type: "EstablishmentLicense",
    id: `lic_${r.license_number}`,
    licenseNumber: r.license_number,
    licenseType: r.license_type,
    licenseSubtype: r.license_subtype ?? null,
    businessName: r.business_name ?? null,
    cityStateZip: r.business_city_state_zip ?? null,
    county: r.business_county,
    expiresOn: r.license_expiration_date_mmddccyy ?? null,
    real: true,
  }))
  .sort((a, b) => (a.licenseNumber < b.licenseNumber ? -1 : a.licenseNumber > b.licenseNumber ? 1 : 0));

const provenance = {
  source: `${RESOURCE}?$where=${WHERE}`,
  dataset: "TDLR All Licenses (Socrata resource 7358-krk7)",
  publisher: "Texas Department of Licensing and Regulation, via the State of Texas Open Data Portal (data.texas.gov)",
  scope:
    "every 'Full Service Establishment' (full-service salon) license with business_county='TRAVIS' — complete within this one-county, one-license-class scope; not a national or all-class corpus",
  retrievedAt: new Date().toISOString(),
  records: licenses.length,
  withheldFields:
    "owner_name, business/owner telephone, street address lines, mailing address, geocode — withheld at wave zero as a recorded curation decision (establishment owner names are frequently personal names of sole proprietors); the source dataset serves them publicly",
  note: "REAL public licensure registry data — never labeled example; the sandbox's synthetic salon and practitioners are checked for non-collision against this corpus",
};

const banner = `/**
 * seed-licenses.js — GENERATED by scripts/ingest-licenses.mjs (do not edit).
 *
 * REAL public data: Texas cosmetology Full Service Establishment (salon)
 * licenses for Travis County, from the TDLR All Licenses open dataset
 * (data.texas.gov, Socrata 7358-krk7), probed reachable keyless in-session
 * on 2026-08-23. Real data is NEVER labeled example; every record carries
 * real:true and the corpus carries its provenance (including the disclosed
 * withheld-fields curation). Reseed: node scripts/ingest-licenses.mjs
 */
`;

const body =
  banner +
  `export const LICENSE_PROVENANCE = ${JSON.stringify(provenance, null, 2)};\n\n` +
  `export const establishmentLicenses = ${JSON.stringify(licenses, null, 2)};\n\n` +
  `export function getEstablishmentLicense(id) {\n` +
  `  return establishmentLicenses.find((x) => x.id === id || x.licenseNumber === id);\n` +
  `}\n`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "..", "seed-licenses.js"), body);
console.log(`ingested ${licenses.length} real establishment licenses (Travis County full-service salons)`);
